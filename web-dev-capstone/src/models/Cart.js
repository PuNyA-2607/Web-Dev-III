import mongoose from 'mongoose';

const cartItemSchema = new mongoose.Schema(
  {
    product: {
      type: mongoose.Schema.Types.ObjectId,
      ref: 'Product',
      required: [true, 'Product reference is required'],
    },
    quantity: {
      type: Number,
      required: [true, 'Quantity is required'],
      min: [1, 'Quantity must be at least 1'],
      validate: {
        validator: Number.isInteger,
        message: 'Quantity must be an integer',
      },
    },
  },
  {
    _id: false, // Items are identified by their product ObjectId
  }
);

const cartSchema = new mongoose.Schema(
  {
    user: {
      type: mongoose.Schema.Types.ObjectId,
      ref: 'User',
      required: [true, 'User reference is required'],
    },
    items: {
      type: [cartItemSchema],
      default: [],
    },
  },
  {
    timestamps: true,
    toJSON: {
      transform: (doc, ret) => {
        delete ret.__v;
        return ret;
      },
    },
  }
);

// ==========================================
// INDEX SPECIFICATION & EXPLANATION
// ==========================================

// Unique Index on user:
// Guarantees strictly one cart per user across the entire system.
// Prevents race conditions or duplicate carts even under concurrent requests.
cartSchema.index({ user: 1 }, { unique: true });

export const Cart = mongoose.model('Cart', cartSchema);
